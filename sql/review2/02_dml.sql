-- =====================================================================
-- 02_dml.sql  -  Review 2 checklist item 2: INSERT, UPDATE, DELETE
--               with before/after state and a row-count table.
--
-- Every statement runs in autocommit mode, so these are real, committed
-- changes. They only touch rows this script creates (user "dml_demo"),
-- and the final DELETE removes them again, so the sandbox ends with
-- exactly the row counts it started with. Seed rows are never modified.
-- Price ticks are not inserted here: ticks enter only via ingest_tick().
-- =====================================================================
\ir _guard.sql

CREATE TEMP VIEW row_counts AS
SELECT (SELECT count(*) FROM users)           AS users,
       (SELECT count(*) FROM watchlists)      AS watchlists,
       (SELECT count(*) FROM watchlist_items) AS watchlist_items,
       (SELECT count(*) FROM alert_rules)     AS alert_rules;

CREATE TEMP VIEW demo_state AS
SELECT u.username, w.name AS watchlist, i.symbol AS item,
       r.rule_id, r.direction, r.threshold, r.cooldown_seconds, r.is_active
FROM users u
LEFT JOIN watchlists w       ON w.user_id = u.user_id
LEFT JOIN watchlist_items wi ON wi.watchlist_id = w.watchlist_id
LEFT JOIN instruments i      ON i.instrument_id = wi.instrument_id
LEFT JOIN alert_rules r      ON r.user_id = u.user_id
WHERE u.username = 'dml_demo'
ORDER BY item;

\echo '===== BEFORE: row counts ====='
SELECT * FROM row_counts;

-- ---------------------------------------------------------------------
\echo '===== 1. INSERT ====='
\echo '1a. a new user (user_id is generated by the identity column)'
INSERT INTO users (username, email)
VALUES ('dml_demo', 'dml_demo@example.com')
RETURNING user_id, username, email;
\set rc_ins_user :ROW_COUNT

\echo '1b. a watchlist for that user (FK user_id looked up by the natural key username)'
INSERT INTO watchlists (user_id, name)
SELECT user_id, 'DML Demo' FROM users WHERE username = 'dml_demo'
RETURNING watchlist_id, user_id, name;
\set rc_ins_list :ROW_COUNT

\echo '1c. two instruments added to the watchlist (composite PK watchlist_id + instrument_id)'
INSERT INTO watchlist_items (watchlist_id, instrument_id)
SELECT w.watchlist_id, i.instrument_id
FROM watchlists w
JOIN users u       ON u.user_id = w.user_id
JOIN instruments i ON i.exchange = 'NSE' AND i.symbol IN ('TCS', 'INFY')
WHERE u.username = 'dml_demo' AND w.name = 'DML Demo'
RETURNING watchlist_id, instrument_id;
\set rc_ins_items :ROW_COUNT

\echo '1d. one alert rule (direction and threshold checked by CHECK constraints)'
INSERT INTO alert_rules (user_id, instrument_id, direction, threshold, cooldown_seconds)
SELECT u.user_id, i.instrument_id, 'ABOVE', 3600, 120
FROM users u
JOIN instruments i ON i.exchange = 'NSE' AND i.symbol = 'TCS'
WHERE u.username = 'dml_demo'
RETURNING rule_id, user_id, instrument_id, direction, threshold, cooldown_seconds, is_active;
\set rc_ins_rule :ROW_COUNT

\echo 'state after INSERT:'
SELECT * FROM demo_state;
SELECT * FROM row_counts;

-- ---------------------------------------------------------------------
\echo '===== 2. UPDATE ====='
\echo '2a. change the rule cooldown and switch the rule off (before -> after)'
SELECT rule_id, cooldown_seconds, is_active
FROM alert_rules r JOIN users u ON u.user_id = r.user_id
WHERE u.username = 'dml_demo';
UPDATE alert_rules r
SET cooldown_seconds = 600, is_active = false
FROM users u
WHERE u.user_id = r.user_id AND u.username = 'dml_demo'
RETURNING r.rule_id, r.cooldown_seconds, r.is_active;
\set rc_upd_rule :ROW_COUNT

\echo '2b. rename the watchlist (UNIQUE(user_id, name) still holds)'
UPDATE watchlists w
SET name = 'DML Demo (renamed)'
FROM users u
WHERE u.user_id = w.user_id AND u.username = 'dml_demo' AND w.name = 'DML Demo'
RETURNING w.watchlist_id, w.name;
\set rc_upd_list :ROW_COUNT

\echo 'state after UPDATE:'
SELECT * FROM demo_state;

-- ---------------------------------------------------------------------
\echo '===== 3. DELETE ====='
\echo '3a. remove INFY from the watchlist'
DELETE FROM watchlist_items wi
USING watchlists w, users u, instruments i
WHERE wi.watchlist_id = w.watchlist_id
  AND w.user_id = u.user_id
  AND i.instrument_id = wi.instrument_id
  AND u.username = 'dml_demo' AND i.symbol = 'INFY'
RETURNING wi.watchlist_id, wi.instrument_id;
\set rc_del_item :ROW_COUNT

\echo 'state after removing INFY:'
SELECT * FROM demo_state;

\echo '3b. delete the user: ON DELETE CASCADE also removes its watchlist, items and rule'
SELECT (SELECT count(*) FROM watchlists w JOIN users u USING (user_id)
         WHERE u.username = 'dml_demo')                                AS demo_watchlists,
       (SELECT count(*) FROM watchlist_items wi
          JOIN watchlists w USING (watchlist_id) JOIN users u USING (user_id)
         WHERE u.username = 'dml_demo')                                AS demo_items,
       (SELECT count(*) FROM alert_rules r JOIN users u USING (user_id)
         WHERE u.username = 'dml_demo')                                AS demo_rules;
DELETE FROM users WHERE username = 'dml_demo'
RETURNING user_id, username;
\set rc_del_user :ROW_COUNT
SELECT count(*) AS dml_demo_rows_left FROM demo_state;

-- ---------------------------------------------------------------------
\echo '===== AFTER: row counts (identical to BEFORE) ====='
SELECT * FROM row_counts;

\echo '===== Row-count summary (psql ROW_COUNT after each statement) ====='
SELECT * FROM (VALUES
    (1, 'INSERT', 'users',           :rc_ins_user),
    (2, 'INSERT', 'watchlists',      :rc_ins_list),
    (3, 'INSERT', 'watchlist_items', :rc_ins_items),
    (4, 'INSERT', 'alert_rules',     :rc_ins_rule),
    (5, 'UPDATE', 'alert_rules',     :rc_upd_rule),
    (6, 'UPDATE', 'watchlists',      :rc_upd_list),
    (7, 'DELETE', 'watchlist_items', :rc_del_item),
    (8, 'DELETE', 'users (+ CASCADE to watchlists, items, rules)', :rc_del_user)
) AS s(step, statement, target_table, rows_affected)
ORDER BY step;
