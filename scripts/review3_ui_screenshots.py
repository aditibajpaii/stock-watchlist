"""Review 3: screenshots of every working module of the web UI.

    python scripts/review3_ui_screenshots.py [base_url]

Needs the app running (uvicorn app.main:app) on a database that has the seed
+ replay data, and Python Playwright. Writes docs/review3/screenshots/UI*.png.
Every action is done through the real UI (clicks and typing), as user arjun.
WARNING: it writes data (a watchlist, a rule, two manual ticks) - point it at
a throwaway or freshly reset database.
"""
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://127.0.0.1:8000"
OUT = Path(__file__).resolve().parent.parent / "docs" / "review3" / "screenshots"
OUT.mkdir(parents=True, exist_ok=True)


def shot(page, name, full=True):
    page.wait_for_timeout(600)
    page.screenshot(path=str(OUT / f"{name}.png"), full_page=full)
    print("saved", name)


def view(page, name):
    page.click(f"nav button[data-view='{name}']")
    page.wait_for_timeout(500)


with sync_playwright() as p:
    try:
        browser = p.chromium.launch()
    except Exception:
        browser = p.chromium.launch(channel="chrome")
    page = browser.new_page(viewport={"width": 1400, "height": 900}, device_scale_factor=1.25)
    page.on("dialog", lambda d: d.dismiss())
    page.goto(BASE + "/")
    page.wait_for_selector("#user-select:not([disabled])")
    arjun = [o for o in page.locator("#user-select option").all_inner_texts() if "arjun" in o][0]
    page.select_option("#user-select", label=arjun)
    page.wait_for_timeout(1000)

    # 1. Dashboard
    view(page, "dashboard")
    shot(page, "UI01_dashboard")

    # 2. Watchlists: create a list, add two instruments
    view(page, "watchlists")
    page.fill("#watchlist-name", "Banking")
    page.click("#watchlist-form button[type=submit]")
    page.wait_for_timeout(800)
    card = page.locator("article.card", has=page.locator("h3", has_text="Banking"))
    for sym in ("HDFCBANK", "TCS"):
        sel = card.locator("select")
        label = [o for o in sel.locator("option").all_inner_texts() if sym in o][0]
        sel.select_option(label=label)
        card.locator("button[type=submit]").click()
        page.wait_for_timeout(800)
    shot(page, "UI02_watchlists")

    # 3. Duplicate name -> UNIQUE (user_id, name) error shown to the user
    page.fill("#watchlist-name", "Crypto")
    page.click("#watchlist-form button[type=submit]")
    page.wait_for_timeout(700)
    shot(page, "UI03_watchlist_duplicate_error", full=False)

    # 4. Alert rules: create HDFCBANK ABOVE 1700, cooldown 0
    view(page, "rules")
    label = [o for o in page.locator("#rule-instrument option").all_inner_texts() if "HDFCBANK" in o][0]
    page.select_option("#rule-instrument", label=label)
    page.select_option("#rule-direction", "ABOVE")
    page.fill("#rule-threshold", "1700")
    page.fill("#rule-cooldown", "0")
    page.click("#rule-form button[type=submit]")
    page.wait_for_timeout(800)
    shot(page, "UI04_alert_rules")

    # 5. Demo / manual tick: 1690 (no crossing) then 1710 (crosses 1700 -> alert)
    view(page, "demo")
    label = [o for o in page.locator("#tick-pick option").all_inner_texts() if "HDFCBANK" in o][0]
    page.select_option("#tick-pick", label=label)
    page.fill("#tick-price", "1690")
    page.fill("#tick-volume", "100")
    page.click("#tick-form button[type=submit]")
    page.wait_for_timeout(1200)
    shot(page, "UI05_manual_tick_no_alert")
    page.fill("#tick-price", "1710")
    page.fill("#tick-volume", "150")
    page.click("#tick-form button[type=submit]")
    page.wait_for_timeout(1500)
    shot(page, "UI06_manual_tick_alert_fired")
    page.click("#tick-resend")
    page.wait_for_timeout(1200)
    shot(page, "UI07_manual_tick_duplicate")

    # 6. Alert history
    view(page, "alerts")
    shot(page, "UI08_alert_history")

    # 7. Instruments: search + latest price & history chart
    view(page, "instruments")
    page.fill("#instrument-search", "reli")
    page.wait_for_timeout(400)
    page.locator("#instruments button", has_text="Latest price").first.click()
    page.wait_for_selector("#instrument-detail svg.chart")
    page.evaluate("window.scrollTo(0, 0)")
    shot(page, "UI09_instrument_search_history")

    # 8. Dashboard again (after the new watchlist, rule and alert)
    view(page, "dashboard")
    page.click("#refresh-button")
    page.wait_for_timeout(1000)
    shot(page, "UI10_dashboard_after")

    # 9. API documentation (Swagger UI generated by FastAPI)
    page.goto(BASE + "/docs")
    page.wait_for_selector(".opblock", timeout=15000)
    shot(page, "UI11_api_docs")
    browser.close()
